export const searchCatalogue = (query) => {
  const q = query.trim().toLowerCase();
  if (!q) return { shops: [], products: [] };
  const matchedShops = shops.filter((shop) =>
    [shop.name, shop.tagline, shop.description, ...shop.highlights, ...shop.sections]
      .join(' ')
      .toLowerCase()
      .includes(q),
  );
  const matchedProducts = allProducts.filter((product) =>
    [product.name, product.description, product.section, product.shopName, ...(product.tags || [])]
      .join(' ')
      .toLowerCase()
      .includes(q),
  );
  return { shops: matchedShops, products: matchedProducts };
};
